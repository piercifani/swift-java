import CodePrinting
import SwiftExtract
import SwiftJavaJNICore

/// With `kotlinOutput`, a Kotlin file per module on top of the generated Java:
/// - `suspend` functions for `async` ones, awaiting the Java method's future. Cancelling the coroutine
///   cancels the future, which cancels the Swift task;
/// - `Flow`s for functions returning an `AsyncStream`; collecting one iterates the stream, and cancelling
///   the collection cancels the Swift task;
/// - extension functions for the members an extension adds to another module's type;
/// - `suspending { }`, which runs a suspend lambda as a closure Swift awaits.
extension JNISwift2JavaGenerator {
  /// Prints the module's Kotlin file, or returns `nil` when it has nothing to add to the Java.
  func printKotlinFile(_ printer: inout JavaPrinter) -> String? {
    var functions: [String] = []
    var helpers: Set<KotlinHelper> = []
    for type in analysis.extractedTypes.values.sorted(by: { $0.effectiveJavaName < $1.effectiveJavaName }) {
      let isOtherModulesType = type.swiftNominal.moduleName != swiftModuleName
      for method in type.methods where !method.isStatic {
        if let function = suspendFunction(method, receiver: type.effectiveJavaName) {
          functions.append(function)
        } else if let function = flowFunction(method, receiver: type.effectiveJavaName) {
          functions.append(function)
          helpers.insert(.asFlow)
        } else if isOtherModulesType, let function = extensionFunction(method, of: type) {
          functions.append(function)
          helpers.insert(.borrowingArena)
        }
      }
    }
    for function in analysis.extractedGlobalFuncs {
      if let function = suspendFunction(function, receiver: nil) {
        functions.append(function)
      } else if let function = flowFunction(function, receiver: nil) {
        functions.append(function)
        helpers.insert(.asFlow)
      }
    }
    if hasAsyncClosureParameters {
      helpers.insert(.suspending)
    }
    guard !functions.isEmpty || !helpers.isEmpty else {
      return nil
    }

    printer.print(
      """
      // Generated by jextract-swift
      // Swift module: \(swiftModuleName)

      package \(javaPackage)

      import kotlinx.coroutines.future.await\(helpers.contains(.asFlow) ? "\nimport kotlinx.coroutines.channels.awaitClose\nimport kotlinx.coroutines.channels.trySendBlocking" : "")\(helpers.contains(.suspending) ? "\nimport kotlinx.coroutines.future.future" : "")

      """
    )
    printer.print((functions + helpers.sorted(by: { $0.rawValue < $1.rawValue }).map(\.source)).joined(separator: "\n\n"))
    return "\(swiftModuleName)Kotlin.kt"
  }

  enum KotlinHelper: String {
    case asFlow, borrowingArena, suspending

    var source: String {
      switch self {
      case .asFlow:
        """
        /** Iterates the Swift stream while the flow is collected; cancelling the collection cancels the Swift task. */
        private fun <T> org.swift.swiftkit.core.SwiftAsyncStream<T>.asFlow(): kotlinx.coroutines.flow.Flow<T> =
          kotlinx.coroutines.flow.callbackFlow {
            val subscription = subscribe(object : org.swift.swiftkit.core.SwiftAsyncStream.Subscriber<T> {
              override fun onNext(value: T) {
                trySendBlocking(value)
              }

              override fun onComplete() {
                close()
              }

              override fun onError(error: Throwable) {
                close(error)
              }
            })
            awaitClose { subscription.cancel() }
          }
        """
      case .borrowingArena:
        """
        /** Wraps a Swift value another wrapper owns, for the duration of a call. */
        private object BorrowingArena : org.swift.swiftkit.core.SwiftArena {
          override fun register(instance: org.swift.swiftkit.core.SwiftInstance) {}
        }
        """
      case .suspending:
        """
        /**
         * Runs `block` as an `async` closure implemented in Kotlin, which returns nothing: Swift awaits the returned
         * future. It starts on the thread Swift calls the closure on.
         */
        fun suspending(block: suspend kotlinx.coroutines.CoroutineScope.() -> Unit): java.util.concurrent.CompletableFuture<Void?> =
          kotlinx.coroutines.CoroutineScope(kotlinx.coroutines.Dispatchers.Unconfined).future {
            block()
            null
          }

        /** Runs `block` as an `async` closure implemented in Kotlin, which returns its result. */
        fun <T> suspendingValue(block: suspend kotlinx.coroutines.CoroutineScope.() -> T): java.util.concurrent.CompletableFuture<T> =
          kotlinx.coroutines.CoroutineScope(kotlinx.coroutines.Dispatchers.Unconfined).future(block = block)
        """
      }
    }
  }

  /// Whether a function or initializer of this module takes an `async` closure, which Kotlin implements with
  /// `suspending { }`.
  private var hasAsyncClosureParameters: Bool {
    let functions = analysis.extractedGlobalFuncs + analysis.extractedTypes.values.flatMap { $0.methods + $0.initializers }
    return functions.contains { function in
      function.functionSignature.parameters.contains {
        if case .function(let functionType) = $0.type { functionType.isAsync } else { false }
      }
    }
  }

  /// `fun Receiver.name(…): Flow<T>`, for a function returning an `AsyncStream`, translated as `<name>Stream`.
  private func flowFunction(_ decl: ExtractedFunc, receiver: String?) -> String? {
    guard let translated = translatedDecl(for: decl), translated.name.hasSuffix("Stream"),
      JavaTranslation.asyncStreamElementType(decl.functionSignature.result.type) != nil,
      case .class(_, _, let streamTypeArguments) = translated.translatedFunctionSignature.result.javaType,
      let elementType = streamTypeArguments.first.flatMap({ kotlinTypeName($0, isNullable: false) }),
      let (parameters, arguments) = kotlinParameters(translated, decl)
    else {
      return nil
    }
    let name = String(translated.name.dropLast("Stream".count))
    let receiverPrefix = receiver.map { "\($0)." } ?? ""
    let call = "\(receiver == nil ? "\(swiftModuleName)." : "")\(translated.name)(\(arguments.joined(separator: ", "))).asFlow()"
    return "fun \(receiverPrefix)\(name)(\(parameters.joined(separator: ", "))): kotlinx.coroutines.flow.Flow<\(elementType)> =\n  \(call)"
  }

  /// `fun OtherModulesType.name(…)`, for a method an extension in this module adds to another module's type:
  /// it wraps the receiver's Swift value in this module's class for the type, without owning it.
  private func extensionFunction(_ decl: ExtractedFunc, of type: ExtractedNominalType) -> String? {
    guard let translated = translatedDecl(for: decl), !translated.isAsync,
      let receiverPackage = moduleJavaPackages[type.swiftNominal.moduleName],
      let (parameters, arguments) = kotlinParameters(translated, decl)
    else {
      return nil
    }
    let signature = translated.translatedFunctionSignature
    let resultType: String
    if decl.functionSignature.result.type.isVoid {
      resultType = "Unit"
    } else if let type = kotlinTypeName(signature.result.javaType, isNullable: JavaTranslation.isOptional(decl.functionSignature.result.type)) {
      resultType = type
    } else {
      return nil
    }
    let receiver = "\(receiverPackage).\(type.effectiveJavaName)"
    let wrapper = "\(type.effectiveJavaName).wrapMemoryAddressUnsafe(`$memoryAddress`(), BorrowingArena)"
    return "fun \(receiver).\(translated.name)(\(parameters.joined(separator: ", "))): \(resultType) =\n  \(wrapper).\(translated.name)(\(arguments.joined(separator: ", ")))"
  }

  /// The Kotlin parameters of a translated function and the arguments that pass them on, or `nil` when
  /// one isn't spelled (generic parameters).
  private func kotlinParameters(_ translated: TranslatedFunctionDecl, _ decl: ExtractedFunc) -> ([String], [String])? {
    var parameters: [String] = []
    var arguments: [String] = []
    for (translatedParameter, parameter) in zip(translated.translatedFunctionSignature.parameters, decl.functionSignature.parameters) {
      guard case .concrete(let javaType) = translatedParameter.parameter.type,
        let type = kotlinTypeName(javaType, isNullable: JavaTranslation.isOptional(parameter.type))
      else {
        return nil
      }
      parameters.append("\(translatedParameter.parameter.name): \(type)")
      arguments.append(translatedParameter.parameter.name)
    }
    if translated.translatedFunctionSignature.requiresSwiftArena && !config.effectiveMemoryManagementMode.requiresGlobalArena {
      parameters.append("swiftArena: org.swift.swiftkit.core.SwiftArena")
      arguments.append("swiftArena")
    }
    return (parameters, arguments)
  }

  /// `suspend fun Receiver.name(…)`, or a top-level `suspend fun name(…)` for a module function, awaiting
  /// the `<name>Async` Java method's future.
  private func suspendFunction(_ decl: ExtractedFunc, receiver: String?) -> String? {
    guard config.effectiveAsyncFuncMode == .completableFuture,
      let translated = translatedDecl(for: decl), translated.isAsync, translated.name.hasSuffix("Async")
    else {
      return nil
    }
    let signature = translated.translatedFunctionSignature
    guard let (parameters, arguments) = kotlinParameters(translated, decl) else {
      return nil
    }

    guard case .class(_, _, let futureTypeArguments) = signature.result.javaType,
      let futureValueType = futureTypeArguments.first
    else {
      return nil
    }
    let resultType: String
    if decl.functionSignature.result.type.isVoid {
      resultType = "Unit"
    } else if let type = kotlinTypeName(futureValueType, isNullable: JavaTranslation.isOptional(decl.functionSignature.result.type)),
      !type.hasPrefix("java.util.Optional")
    {
      resultType = type
    } else {
      return nil
    }

    let name = String(translated.name.dropLast("Async".count))
    let receiverPrefix = receiver.map { "\($0)." } ?? ""
    let call = "\(receiver == nil ? "\(swiftModuleName)." : "")\(translated.name)(\(arguments.joined(separator: ", "))).await()"
    let body = resultType == "Unit" ? "{\n  \(call)\n}" : "=\n  \(call)"
    return "suspend fun \(receiverPrefix)\(name)(\(parameters.joined(separator: ", "))): \(resultType) \(body)"
  }

  /// The Kotlin spelling of a Java type, or `nil` for one this file doesn't spell.
  private func kotlinTypeName(_ type: JavaType, isNullable: Bool) -> String? {
    let name: String
    switch type {
    case .boolean: name = "Boolean"
    case .byte: name = "Byte"
    case .char: name = "Char"
    case .short: name = "Short"
    case .int: name = "Int"
    case .long: name = "Long"
    case .float: name = "Float"
    case .double: name = "Double"
    case .void: name = "Unit"
    case .array(let element):
      switch element {
      case .boolean: name = "BooleanArray"
      case .byte: name = "ByteArray"
      case .char: name = "CharArray"
      case .short: name = "ShortArray"
      case .int: name = "IntArray"
      case .long: name = "LongArray"
      case .float: name = "FloatArray"
      case .double: name = "DoubleArray"
      default:
        guard let elementName = kotlinTypeName(element, isNullable: false) else {
          return nil
        }
        name = "Array<\(elementName)>"
      }
    case .class(let package, let className, let typeParameters):
      switch (package, className) {
      case ("java.lang", "String"), (nil, "String"): name = "String"
      case ("java.lang", "Long"): name = "Long"
      case ("java.lang", "Integer"): name = "Int"
      case ("java.lang", "Double"): name = "Double"
      case ("java.lang", "Boolean"): name = "Boolean"
      case ("java.lang", "Void"): name = "Unit"
      case ("java.lang", "Object"): name = "Any"
      default:
        let arguments = typeParameters.compactMap { kotlinTypeName($0, isNullable: false) }
        guard arguments.count == typeParameters.count else {
          return nil
        }
        let qualified = package.map { "\($0).\(className)" } ?? className
        name = arguments.isEmpty ? qualified : "\(qualified)<\(arguments.joined(separator: ", "))>"
      }
    }
    return isNullable ? "\(name)?" : name
  }
}
